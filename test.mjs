#!/usr/bin/env node
/**
 * test.mjs — השער של הפרויקט. מריצים אותו אחרי כל שינוי.
 *
 *   node test.mjs            הרצה רגילה
 *   node test.mjs --negative בקרה שלילית: משבש את הטבלה ומוודא שהשער נופל
 *
 * שלושה דברים נבדקים כאן, והשלישי הוא הסיבה שהקובץ קיים:
 *   ① החישוב מחזיר בדיוק את מה שהגיליון של החברה חישב, 126 תאים.
 *   ② פיצול התשלומים מסתכם בדיוק לסך הכול, בלי אגורה שנעלמת.
 *   ③ הטבלה שבתוך index.html זהה לקובץ הנתונים.
 *      🔴 בלי הבדיקה הזו, עדכון אחוזים ב-fee-table.json היה משאיר את
 *         הדף עצמו מאחור בשקט, והמוכר היה רואה מספר ישן.
 */
import { readFileSync, existsSync } from 'node:fs';
import { paymentsFee, quote, PCT, MIN_PAYMENTS, MAX_PAYMENTS } from './payments-fee.mjs';

const NEGATIVE = process.argv.includes('--negative');
let pass = 0, fail = 0;
const ok = (cond, msg) => { cond ? pass++ : (fail++, console.log('  ✗ ' + msg)); return cond; };

/* ── ① מול הגיליון שהתקבל ────────────────────────────────────────────
   אלה המכפלות הגולמיות שאקסל עצמו חישב, לפני העיגול. הן ההוכחה
   שהאחוזים נקראו נכון ולא הוקלדו מחדש בטעות. */
const AMOUNTS = [2000, 3000, 4000, 5000, 6000, 7000];
const SHEET = {
  4:[45,67.5,90,112.5,135,157.5],              5:[48.86,73.29,97.72,122.15,146.58,171.01],
  6:[52.72,79.08,105.44,131.8,158.16,184.52],  7:[56.56,84.84,113.12,141.4,169.68,197.96],
  8:[60.5,90.75,121,151.25,181.5,211.75],      9:[64.22,96.33,128.44,160.55,192.66,224.77],
 10:[68.04,102.06,136.08,170.1,204.12,238.14],11:[71.84,107.76,143.68,179.6,215.52,251.44],
 12:[75.64,113.46,151.28,189.1,226.92,264.74],13:[81.48,122.22,162.96,203.7,244.44,285.18],
 14:[85.42,128.13,170.84,213.55,256.26,298.97],15:[89.32,133.98,178.64,223.3,267.96,312.62],
 16:[93.24,139.86,186.48,233.1,279.72,326.34],17:[97.14,145.71,194.28,242.85,291.42,339.99],
 18:[101.02,151.53,202.04,252.55,303.06,353.57],19:[105.08,157.62,210.16,262.7,315.24,367.78],
 20:[116.56,174.84,233.12,291.4,349.68,407.96],21:[120.78,181.17,241.56,301.95,362.34,422.73],
 22:[124.98,187.47,249.96,312.45,374.94,437.43],23:[129.18,193.77,258.36,322.95,387.54,452.13],
 24:[133.38,200.07,266.76,333.45,400.14,466.83],
};

let table = { ...PCT };
if (NEGATIVE) table[12] = table[12] + 1;   // שיבוש מכוון של אחוז אחד

console.log('① מול 126 תאי הגיליון');
let cells = 0;
for (const [n, row] of Object.entries(SHEET)) {
  AMOUNTS.forEach((amt, i) => {
    cells++;
    const raw = (amt * table[n]) / 100000;               // המכפלה הגולמית
    ok(Math.abs(raw - row[i]) < 1e-9, `n=${n} amt=${amt}: ${raw} במקום ${row[i]}`);
    /* והתוצאה הסופית: עיגול כלפי מעלה לעשרות של אותה מכפלה */
    const expected = Math.ceil(row[i] / 10) * 10;
    if (!NEGATIVE) ok(paymentsFee(amt, +n).fee === expected,
      `n=${n} amt=${amt}: תוספת ${paymentsFee(amt, +n).fee} במקום ${expected}`);
  });
}
console.log(`   נבדקו ${cells} תאים`);

/* ── ② התשלום החודשי ואחוז התוספת ──────────────────────────────────
   התוספת מתחלקת שווה בשווה, ולכן `monthly * n` חייב להיות בדיוק
   סך הכול. ‏`pct` הוא האחוז בפועל אחרי העיגול, ולא האחוז שבטבלה. */
console.log('② התשלום החודשי ואחוז התוספת');
let combos = 0;
for (let amt = 100; amt <= 50000; amt += 137) {
  for (let n = MIN_PAYMENTS; n <= MAX_PAYMENTS; n++) {
    const q = quote(amt, n);
    combos++;
    ok(Math.abs(q.monthly * n - q.total) < 1e-9, `${amt} ב-${n}: ${q.monthly}×${n} אינו ${q.total}`);
    ok(q.fee % 10 === 0, `${amt} ב-${n}: התוספת ${q.fee} אינה עגולה בעשרות`);
    ok(q.fee >= 0, `${amt} ב-${n}: תוספת שלילית`);
    ok(Math.abs(q.pct - (q.fee / amt) * 100) < 1e-9, `${amt} ב-${n}: אחוז התוספת שגוי`);
    /* העיגול כלפי מעלה אינו יכול להוזיל, ולכן האחוז בפועל
       תמיד גדול או שווה לאחוז שבטבלה. */
    ok(q.pct >= q.tablePct - 1e-9, `${amt} ב-${n}: ${q.pct}% נמוך מהטבלה ${q.tablePct}%`);
  }
}
console.log(`   נבדקו ${combos} צירופים`);

/* ── ③ הטבלה זהה בכל המקומות שמחזיקים אותה ────────────────────────── */
console.log('③ אין סחיפה בין קובץ הנתונים לדף');
const json = JSON.parse(readFileSync(new URL('./data/fee-table.json', import.meta.url), 'utf8')).table;

/* הטבלה בדף יושבת בבלוק JSON מסומן, ולכן נשלפת במלואה ולא ברגקס
   על קוד. רגקס על קוד היה עלול להתאים למספרים אחרים ולהחזיר ירוק כוזב. */
const page = readFileSync(new URL('./index.html', import.meta.url), 'utf8');
const block = page.match(/<script id="fee-table"[^>]*>([\s\S]*?)<\/script>/);
if (!block) { console.log('  ✗ לא נמצא בלוק fee-table ב-index.html'); process.exit(1); }
const html = JSON.parse(block[1]);

for (const [n, v] of Object.entries(json)) {
  ok(html[n] === v, `index.html: ${n} תשלומים = ${html[n]} ולא ${v}`);
}
/* שער נגד "עבר כי לא נמצא כלום" */
ok(Object.keys(html).length === Object.keys(json).length,
   `index.html מחזיק ${Object.keys(html).length} שורות ולא ${Object.keys(json).length}`);

/* ── ④ קצוות ───────────────────────────────────────────────────────── */
console.log('④ קצוות');
ok(paymentsFee(4000, 3).fee === 0, '3 תשלומים אמור להיות בלי תוספת');
ok(paymentsFee(4000, 3).reason !== null, '3 תשלומים אמור להחזיר נימוק');
ok(paymentsFee(4000, 25).reason !== null, '25 תשלומים אמור להיחסם');
ok(paymentsFee(0, 12).fee === 0, 'סכום 0 אמור להחזיר תוספת 0');
ok(paymentsFee(-5, 12).reason !== null, 'סכום שלילי אמור להיפסל');
ok(paymentsFee(4000, 12.5).reason !== null, 'מספר תשלומים לא שלם אמור להיפסל');
ok(paymentsFee(150, 24).fee === 20, 'המדרגה: 150 ש"ח ב-24 תשלומים = 20 ולא 10');
ok(paymentsFee(149, 24).fee === 10, 'המדרגה: 149 ש"ח ב-24 תשלומים = 10');
ok(paymentsFee(1499.9, 12).fee === 60, 'אגורות בקלט: 1499.90 ב-12 = 60');
{
  const q = quote(4000, 12);
  ok(q.fee === 160,                     'הדוגמה: 4,000 ב-12 ⟵ תוספת 160');
  ok(q.total === 4160,                  'הדוגמה: סך הכול 4,160');
  ok(Math.abs(q.monthly - 4160 / 12) < 1e-9, 'הדוגמה: כל תשלום 346.67');
  ok(Math.abs(q.pct - 4) < 1e-9,        'הדוגמה: אחוז התוספת בפועל 4.00%');
  ok(Math.abs(q.tablePct - 3.782) < 1e-9, 'הדוגמה: האחוז שבטבלה 3.782%');
}

console.log(`\n${fail === 0 ? '🟢' : '🔴'}  עברו ${pass} · נכשלו ${fail}`);
if (NEGATIVE) {
  const caught = fail > 0;
  console.log(caught
    ? '🟢 בקרה שלילית: השיבוש נתפס, ולכן הבדיקה מודדת ואינה מאשרת את עצמה.'
    : '🔴 בקרה שלילית: השיבוש לא נתפס. הבדיקה חסרת ערך.');
  process.exit(caught ? 0 : 1);
}
process.exit(fail === 0 ? 0 : 1);
